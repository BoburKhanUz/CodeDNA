<?php

declare(strict_types=1);

namespace Tests\Benchmark;

use App\Actions\Snapshots\StoreUploadedSource;
use App\Jobs\ImportGitHubSource;
use App\Models\GitHubImport;
use App\Models\Project;
use App\Models\User;
use App\Support\Sources\SourceArchiveLimits;
use App\Support\Sources\ZipArchiveInspector;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Queue;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Tests\Support\BillingFixtures;
use Tests\Support\FakeGitHub;
use Tests\Support\GitHubFixtures;
use Tests\Support\ZipBuilder;
use Tests\TestCase;

/**
 * Source intake benchmark (Phase 26, docs/performance/benchmarking.md#source-intake).
 * Not part of the default suites; run with `make benchmark-intake`.
 *
 * Measures, per archive profile (generated by scripts/benchmark/make_sources.py,
 * plus a ~45 MB archive near the 50 MiB limit built here): the upload action
 * (inspection, SHA-256, private object storage, snapshot) and a GitHub import
 * job (download, inspection, storage, snapshot) against GitHub's test double,
 * so GitHub's own network latency is excluded. Both are timed and their peak
 * PHP memory recorded; memory must stay bounded (streaming), whatever the
 * archive's size.
 */
final class SourceIntakeBenchmarkTest extends TestCase
{
    use RefreshDatabase;

    private const REPEAT = 3;

    private string $prefix;

    private string $work;

    private FakeGitHub $github;

    protected function setUp(): void
    {
        parent::setUp();
        Queue::fake();
        $this->prefix = 'phpunit/bench-'.strtolower((string) Str::ulid()).'/';
        config(['codedna.sources.key_prefix' => $this->prefix]);
        $this->work = sys_get_temp_dir().'/codedna-intake-'.Str::random(8);
        mkdir($this->work);
        // Configured once: it holds the GitHub App key the linked accounts use.
        $this->github = FakeGitHub::configure()->fake();
    }

    protected function tearDown(): void
    {
        Storage::forgetDisk('sources');
        Storage::disk('sources')->deleteDirectory(rtrim($this->prefix, '/'));
        array_map('unlink', glob($this->work.'/*') ?: []);
        @rmdir($this->work);
        parent::tearDown();
    }

    public function test_source_intake_time_and_memory(): void
    {
        $archives = $this->archives();
        $rows = [];
        foreach ($archives as $profile => $path) {
            $upload = $this->measure(fn () => $this->upload($path), self::REPEAT);
            $import = $this->measure(fn () => $this->import($path), self::REPEAT);
            $inspect = $this->measure(fn () => (new ZipArchiveInspector(SourceArchiveLimits::fromConfig((array) config('codedna.sources.limits'))))->inspect($path), self::REPEAT);
            $rows[$profile] = ['bytes' => filesize($path), 'upload' => $upload, 'github_import' => $import, 'inspection' => $inspect];
            // Streaming: the archive is never held in memory, so peak memory
            // grows far less than the archive (generous bound, no timing).
            $this->assertLessThan(24 * 1048576 + (int) (filesize($path) / 4), $upload['peak_bytes'], "{$profile}: upload memory is bounded");
            // GitHub's test double (Http::fake) builds each served archive as one
            // string, so the import's measured peak includes one copy of the
            // archive; the real client streams the body through php://temp
            // (spilled to disk past 2 MB) into the file (GitHubHttp::download).
            $this->assertLessThan(24 * 1048576 + (int) (filesize($path) * 1.25), $import['peak_bytes'], "{$profile}: import memory is bounded");
        }

        $lines = [sprintf('%-11s %10s %20s %20s %20s', 'profile', 'archive KB', 'upload p50 ms / MB', 'import p50 ms / MB', 'inspect p50 ms')];
        foreach ($rows as $profile => $r) {
            $lines[] = sprintf('%-11s %10d %12.1f / %5.1f %12.1f / %5.1f %20.1f', $profile, $r['bytes'] / 1024,
                $r['upload']['p50_ms'], $r['upload']['peak_bytes'] / 1048576, $r['github_import']['p50_ms'], $r['github_import']['peak_bytes'] / 1048576, $r['inspection']['p50_ms']);
        }
        fwrite(STDERR, "\n".implode("\n", $lines)."\n");
        if (($out = getenv('BENCH_OUTPUT')) !== false && $out !== '') {
            file_put_contents($out, json_encode($rows, JSON_PRETTY_PRINT | JSON_THROW_ON_ERROR)."\n");
        }
    }

    /** @return array<string, string> */
    private function archives(): array
    {
        $dir = (string) (getenv('BENCH_SOURCES') ?: storage_path('app/benchmark/sources'));
        $archives = [];
        foreach (['small', 'medium', 'large', 'xlarge'] as $profile) {
            if (is_file("{$dir}/{$profile}.zip")) {
                $archives[$profile] = "{$dir}/{$profile}.zip";
            }
        }
        $this->assertNotEmpty($archives, "No benchmark archives in {$dir}: run scripts/benchmark/make_sources.py.");

        // Near the 50 MiB archive limit: 9 stored (uncompressed) text files of
        // ~5 MB of generated hex, inside the 25 MiB per-file limit.
        $zip = new ZipBuilder;
        for ($i = 0; $i < 9; $i++) {
            $zip->file("pkg/data_{$i}.py", '# '.implode("\n# ", str_split(bin2hex(random_bytes(2_500_000)), 80))."\n", ['method' => 0]);
        }
        $near = "{$this->work}/near-limit.zip";
        file_put_contents($near, $zip->build());
        unset($zip);
        gc_collect_cycles();
        $archives['near-limit'] = $near;

        return $archives;
    }

    /** @return array{p50_ms: float, peak_bytes: int} */
    private function measure(callable $work, int $repeat): array
    {
        // One untimed run first: the first use of the S3 client loads the AWS
        // SDK's service definitions (~25 MB once per process, whatever the
        // archive), which is not per-archive cost.
        $work();
        $times = [];
        $peak = 0;
        for ($i = 0; $i < $repeat; $i++) {
            gc_collect_cycles();
            $base = memory_get_usage();
            memory_reset_peak_usage();
            $t = hrtime(true);
            $work();
            $times[] = (hrtime(true) - $t) / 1e6;
            $peak = max($peak, memory_get_peak_usage() - $base);
        }
        sort($times);

        return ['p50_ms' => round($times[intdiv(count($times), 2)], 1), 'peak_bytes' => $peak];
    }

    private function upload(string $archive): void
    {
        $user = User::factory()->create();
        BillingFixtures::pro($user);
        $project = Project::factory()->for($user)->create();
        $copy = "{$this->work}/upload.zip";
        copy($archive, $copy);
        app(StoreUploadedSource::class)->handle($project, $user, $copy);
    }

    private function import(string $archive): void
    {
        // A new commit each time (a commit already imported is not stored again).
        $sha = bin2hex(random_bytes(20));
        $this->github->branches[FakeGitHub::REPOSITORY_ID]['main'] = $sha;
        $this->github->archives[$sha] = (string) file_get_contents($archive);
        $user = User::factory()->create();
        BillingFixtures::pro($user);
        $project = Project::factory()->for($user)->create();
        GitHubFixtures::account($user);
        GitHubFixtures::connection($project);
        $id = $this->asUser($user)->postJson("/api/v1/projects/{$project->id}/github/imports")->assertStatus(202)->json('data.id');
        app()->call([new ImportGitHubSource($id), 'handle']);
        unset($this->github->archives[$sha]);
        $done = GitHubImport::query()->findOrFail($id);
        $this->assertSame('SUCCEEDED', $done->status->value, (string) $done->failure_code);
    }
}
